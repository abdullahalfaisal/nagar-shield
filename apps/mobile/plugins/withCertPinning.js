/**
 * The certificate-pinning config plugin.
 *
 * FR-DATA-2: the **production** APK pins the API host's certificate. The
 * `dev` and `preview` profiles deliberately do **not** — a developer must
 * never be locked out by a rotated certificate, and the pinning code path
 * must be inert outside a release build.
 *
 * The plugin writes the Android network-security config at prebuild time:
 *
 *   * `EXPO_PUBLIC_CERT_PIN_PUBLIC_KEYS` is absent or empty → the API host
 *     uses **system trust only**. This is the `dev` / `preview` shape.
 *   * `EXPO_PUBLIC_CERT_PIN_PUBLIC_KEYS` is set → the API host carries a
 *     `<pin-set>` with one `<pin>` per comma-separated digest, alongside the
 *     system certificates (so a pin that is about to expire does not brick
 *     the app while the backup pin is being rolled out).
 *
 * Only the **API host** is pinned. The OSM tile CDN and the EAS update server
 * stay in the default system-trust mode — pinning a third-party CDN breaks
 * the map on every certificate rotation.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { withDangerousMod, withAndroidManifest } = require('@expo/config-plugins');

/** The default API host. Overridable per build. */
const DEFAULT_API_HOST = 'api.supabase.co';

/**
 * The pin set expiry.
 *
 * Android requires an expiry on a `<pin-set>`. A pin set that never expires
 * is a permanent lockout risk if a backup pin is missed, so the expiry is
 * two years out and must be reviewed as part of the release rotation.
 */
const PIN_SET_EXPIRY = '2027-12-31';

/** Where the generated config lands inside the generated Android project. */
const NETWORK_SECURITY_PATH = 'app/src/main/res/xml/network_security_config.xml';

/**
 * Splits the pin set into individual digests.
 *
 * The value is a comma-separated list of base64 SHA-256 subject-public-key
 * digests. A digest may already carry the `sha256/` prefix; a bare digest
 * gets it.
 */
function parsePins(raw) {
  if (!raw) return [];

  return raw
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => (entry.startsWith('sha256/') ? entry : `sha256/${entry}`));
}

/**
 * Builds the network-security XML.
 *
 * `pins` empty → system trust only. `pins` present → system trust plus the
 * pin set.
 */
function buildNetworkSecurityXml(apiHost, pins) {
  const pinElements = pins
    .map((digest) => `                <pin digest="${digest}" />`)
    .join('\n');

  const pinSet = pins.length
    ? `\n            <pin-set expiration="${PIN_SET_EXPIRY}">\n${pinElements}\n            </pin-set>`
    : '';

  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by apps/mobile/plugins/withCertPinning.js — do not edit by hand.

  The API host is pinned only when EXPO_PUBLIC_CERT_PIN_PUBLIC_KEYS is set.
  ${
    pins.length
      ? `This build carries ${pins.length} pin(s).`
      : 'This build has no pin set: the API host uses system trust only.'
  }
  Every other host — the OSM tile CDN, the EAS update server — stays in the
  default system-trust mode, because pinning a third-party CDN would break
  the map on every certificate rotation.
-->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>

    <domain-config cleartextTrafficPermitted="false">
        <domain includeSubdomains="true">${apiHost}</domain>
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>${pinSet}
    </domain-config>
</network-security-config>
`;
}

/**
 * Writes the network-security config into the generated Android project.
 */
function withCertPinning(config) {
  const apiHost = process.env.EXPO_PUBLIC_API_HOST || DEFAULT_API_HOST;
  const pins = parsePins(process.env.EXPO_PUBLIC_CERT_PIN_PUBLIC_KEYS);

  // Cleartext traffic is off for every profile — the app talks TLS only.
  config = withAndroidManifest(config, (androidConfig) => {
    const application = androidConfig.modResults.manifest.application?.[0];
    if (application) {
      application.$['android:usesCleartextTraffic'] = 'false';
    }
    return androidConfig;
  });

  config = withDangerousMod(config, [
    'android',
    async (androidConfig) => {
      const xmlDirectory = path.join(androidConfig.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      const xmlFile = path.join(xmlDirectory, 'network_security_config.xml');

      await fs.promises.mkdir(xmlDirectory, { recursive: true });
      await fs.promises.writeFile(xmlFile, buildNetworkSecurityXml(apiHost, pins), 'utf8');

      return androidConfig;
    },
  ]);

  return config;
}

module.exports = withCertPinning;
module.exports.buildNetworkSecurityXml = buildNetworkSecurityXml;
module.exports.parsePins = parsePins;
