-- =============================================================================
-- Nagar Shield — MVP Phase 1
-- 20261105000021_password_reset_otp.sql
--
-- The password-reset OTP challenge, and the RPCs that own it.
--
-- The story
-- --------
-- `002-identity / 003-email-otp-password-reset`:
--
--   * AC #3 — "an OTP submitted more than 10 minutes after the challenge was
--     issued → the attempt is rejected with `VALIDATION_FAILED` and the
--     password is unchanged";
--   * AC #4 — "an incorrect OTP, confirmed three times → the challenge enters
--     a 30-minute cooldown during which every further attempt is rejected
--     server-side";
--   * AC #5 — "the rejection happens server-side even if the client-side timer
--     is bypassed, and the response carries the remaining cooldown in
--     `details.retry_after_sec`";
--   * AC #8 — "an identifier that matches no account → the same generic
--     response is shown as for a registered address, and no account-existence
--     signal is returned".
--
-- Who owns what
-- -------------
-- **This table owns the code. GoTrue owns the session.**
--
-- That split is not a preference — it is what the local stack forces, and the
-- first implementation of this migration got it wrong. The correction is
-- recorded here in full, because the wrong version looks correct.
--
-- The first version said "GoTrue owns the code": the Edge Function asked
-- `POST /admin/generate_link` for a recovery token, and handed the returned
-- `hashed_token` to `POST /verify` together with the code the user typed.
--
-- **That does not work, and it fails open.** Proved live against the local
-- stack:
--
--   POST /auth/v1/verify  {"type":"recovery","token_hash":"41206be8…","code":"000000"}
--   → 200 {"access_token":"eyJ…","refresh_token":"…"}
--
-- A deliberately wrong code — `000000`, against a code of `152124` — returned
-- a **full session**. GoTrue's `verify` accepts a `token_hash` and a `type`
-- and nothing else; when a `token_hash` is present the code is never
-- compared. The attempt counter was the only thing standing between an
-- attacker and a password reset.
--
-- GoTrue's `verify` has exactly two accepted shapes, both proven live:
--
--   * `{"type":"recovery","token_hash":"…"}`  → a session, **code ignored**;
--   * `{"type":"recovery","token":"…"}`       → a session, **code ignored**;
--
-- and both reject anything else with `"Only the token_hash and type should be
-- provided"` or `"Verify requires either a token or a token hash"`. There is
-- no shape in which GoTrue checks a 6-digit code against a recovery token.
-- The `email_otp` in the `generate_link` response is *not* redeemable
-- through `verify`; it is a display value for a mail template.
--
-- So the code comparison is ours to make. That is the whole point of this
-- table:
--
--   * **The code lives here**, as a bcrypt hash (`code_hash`). The plaintext
--     exists only in the Edge Function's memory, long enough to be put in a
--     mail body, and then it is gone. There is no `code` column, so a dump
--     of this table cannot complete a reset.
--
--   * **The comparison happens here**, in `check_password_reset_otp_state`,
--     against `extensions.crypt(p_code, code_hash)`. The plaintext code never
--     leaves the function.
--
--   * **The session is GoTrue's.** Once our comparison succeeds, the Edge
--     Function redeems the GoTrue recovery token, and GoTrue issues the
--     session. The password is then applied to *that* session through
--     `PUT /auth/v1/user`. Nothing is written to `auth.users` directly, and
--     no session is forged.
--
-- The ordering matters, and it is the security property:
--
--     code → our bcrypt comparison → GoTrue token redemption → session
--
-- The GoTrue token is redeemed **only after** the code has been proven
-- correct. A wrong code never touches GoTrue's token, so the recovery token
-- cannot be burned by a guess, and cannot be redeemed without the code.
--
-- Why not use GoTrue's `email_otp` at all?
-- ----------------------------------------
-- Because GoTrue will not check it, and because its mail template renders a
-- **link**, not a bare code. The local stack's `generate_link` call sends
-- "Reset your password — Follow the link below to choose a new one" with the
-- recovery token in the URL. The 6-digit `email_otp` appears nowhere in the
-- delivered message. So the code the app asks the user to type is a code
-- the mail does not contain.
--
-- The code in this migration is **ours**: generated by the Edge Function,
-- hashed here, and delivered by the app's own mail path. The story asks for
-- an OTP the user types; the OTP has to come from somewhere the user can
-- read it.
--
-- The three rules, and where each lives
-- -------------------------------------
-- All three live here, and all three are enforced by this database:
--
--   * 10-minute validity  → `expires_at`.
--   * 3 attempts          → `attempts`, incremented here.
--   * 30-minute cooldown  → `cooldown_until` / `cooldown_expires_at`, set here
--     when `attempts` passes the limit.
--
-- The cooldown is checked **before** the code is compared, so a challenge in
-- cooldown rejects *every* attempt — including a correct one — and the
-- rejection carries the remaining wait.
--
-- The no-oracle rule
-- ------------------
-- `start_password_reset_otp` raises `AUTH_REQUIRED` for an unknown
-- identifier, and the Edge Function turns that into the same generic
-- `{"sent": true}` it returns for a known one. The *question* stays in the
-- database, where it belongs; the *answer* is identical for every caller,
-- which is the part the user can observe.
--
-- The forward-only rule
-- ---------------------
-- Migrations are never edited once applied. This is a new file, and it has
-- not been applied to any shared database — so the correction described
-- above is made *in this file* rather than in a follow-up migration.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- The challenge table
-- -----------------------------------------------------------------------------
--
-- One row per issued challenge. A **new** challenge supersedes the previous
-- one for the same account: the story's edge-case table says "only the newest
-- challenge is valid; the previous code is rejected as invalid rather than
-- accepted". Superseding is enforced by the partial unique index below.
--
-- The table holds no email address of its own... except that it must: the
-- Edge Function needs the address to redeem the GoTrue token. It is PII, so
-- it is never logged and never returned to a client.

create table if not exists public.password_reset_challenges (
  id uuid primary key default gen_random_uuid(),

  -- The account the challenge belongs to. `profiles.id` is the application
  -- identity (migration 016), so a soft-deleted account's challenges are
  -- removed when the profile row goes.
  user_id uuid not null references public.profiles (id) on delete cascade,

  -- The email GoTrue knows the account by. It is needed to call `POST
  -- /verify`, which identifies the account by address.
  --
  -- It is PII, so it is never logged and never returned to a client.
  account_email text not null,

  -- The **hash of the 6-digit code**. bcrypt, via pgcrypto's `crypt`.
  --
  -- The plaintext code is never stored, here or anywhere else. The
  -- comparison happens in `check_password_reset_otp_state`, which takes the
  -- submitted code as an argument and never returns it.
  --
  -- bcrypt's cost factor is deliberately the pgcrypto default. The code
  -- space is a million, so a fast hash would be brute-forceable offline
  -- from a table dump; bcrypt's slowness is what makes that impractical.
  code_hash text not null,

  -- The GoTrue recovery token, redeemed **after** the code is proven
  -- correct. GoTrue stores it in `auth.one_time_tokens.token_hash`; what
  -- `generate_link` returns as `hashed_token` is that same value.
  --
  -- It is a one-time credential, and it is only worth anything once the
  -- code has been checked.
  token_hash text not null,

  -- The challenge expires here — 10 minutes after issue (FR-AUTH-3). This is
  -- checked here as well as by GoTrue, so an expired challenge is refused
  -- before the code is compared.
  expires_at timestamptz not null,

  -- How many times the code has been entered incorrectly.
  attempts integer not null default 0,

  -- After three failures the challenge is in cooldown until this instant.
  -- NULL means "not in cooldown".
  cooldown_until timestamptz,

  -- The cooldown expires 30 minutes after it was entered.
  cooldown_expires_at timestamptz,

  -- Set when the code is used. The challenge is then invalid, and the
  -- partial unique index no longer covers it.
  consumed_at timestamptz,

  created_at timestamptz not null default now()
);

comment on table public.password_reset_challenges is
  'FR-AUTH-3 — the password-reset OTP challenge. It owns the code (as a bcrypt hash), the attempt counter, the 10-minute validity window and the 30-minute cooldown. GoTrue owns the session, which is issued only after the code has been proven correct here.';

comment on column public.password_reset_challenges.code_hash is
  'The bcrypt hash of the 6-digit code. The plaintext code is never stored, here or anywhere else, and the comparison happens inside `check_password_reset_otp_state`.';

comment on column public.password_reset_challenges.token_hash is
  'The GoTrue recovery token, redeemed only after the code is proven correct. A one-time credential; worthless without the code.';

comment on column public.password_reset_challenges.attempts is
  'Incorrect-code attempts. At 3 the challenge enters a 30-minute cooldown. Never incremented by the client.';

comment on column public.password_reset_challenges.cooldown_until is
  'When the cooldown began. NULL when the challenge is not in cooldown.';

comment on column public.password_reset_challenges.cooldown_expires_at is
  'When the cooldown ends. 30 minutes after `cooldown_until`.';

comment on column public.password_reset_challenges.consumed_at is
  'Set when the code is used. The challenge is then invalid, and the partial unique index no longer covers it.';

-- -----------------------------------------------------------------------------
-- Only one live challenge per account
-- -----------------------------------------------------------------------------
--
-- A new challenge supersedes the old one rather than sitting beside it. This
-- is what makes "only the newest challenge is valid" a structural fact rather
-- than a rule the RPC has to remember to enforce.
--
-- The index is **partial**: it covers the rows that are still live, so the
-- constraint disappears the moment a challenge is consumed or deleted.

create unique index if not exists password_reset_challenges_one_live_per_user
  on public.password_reset_challenges (user_id)
  where consumed_at is null;

-- -----------------------------------------------------------------------------
-- RLS
-- -----------------------------------------------------------------------------
--
-- The table is **server-only**. No client reads it and no client writes it.
-- Both RPCs that touch it are `SECURITY DEFINER`, so the client's own
-- privileges never apply to the table itself.
--
-- Enabling RLS with no policy is the belt-and-braces version: even a client
-- holding the service-role key would have to go through the RPC.

alter table public.password_reset_challenges enable row level security;

