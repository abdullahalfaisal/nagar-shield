create or replace function public.password_reset_otp_ttl_minutes()
returns integer
language sql
immutable
as $$
  select 10;
$$;

create or replace function public.password_reset_otp_max_attempts()
returns integer
language sql
immutable
as $$
  select 3;
$$;

create or replace function public.password_reset_otp_cooldown_minutes()
returns integer
language sql
immutable
as $$
  select 30;
$$;

-- -----------------------------------------------------------------------------
-- password_reset_code_hash
-- -----------------------------------------------------------------------------
--
-- Hashes a 6-digit code with bcrypt.
--
-- pgcrypto's `crypt` generates its own salt when given one argument, so two
-- calls with the same code produce different hashes — which is what a
-- verifier needs. `gen_salt('bf')` is the explicit form of the same thing.
--
-- `set search_path` names the `extensions` schema because that is where
-- pgcrypto lives in a Supabase project. Without it, the function is created
-- with `search_path = public` and `crypt` does not resolve.

create or replace function public.password_reset_code_hash(p_code text)
returns text
language sql
volatile
set search_path = public, extensions
as $$
  select extensions.crypt(btrim(coalesce(p_code, '')), extensions.gen_salt('bf'));
$$;

revoke execute on function public.password_reset_code_hash(text) from public, anon, authenticated;
grant execute on function public.password_reset_code_hash(text) to service_role;

comment on function public.password_reset_code_hash(text) is
  'Hashes a 6-digit password-reset code with bcrypt. The plaintext code is not stored anywhere. Service-role only.';

-- -----------------------------------------------------------------------------
-- start_password_reset_otp
-- -----------------------------------------------------------------------------
--
-- Records a challenge and returns the details the Edge Function needs to
-- finish the job.
--
-- The function is `SECURITY DEFINER` and granted to `service_role` only, so
-- a client cannot call it and register a challenge for somebody else's
-- account.
--
-- The Edge Function supplies the code's bcrypt hash and the GoTrue recovery
-- token. The database never sees the plaintext code.

create or replace function public.start_password_reset_otp(
  p_identifier text,
  p_account_email text,
  p_code_hash text,
  p_token_hash text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_trimmed text := btrim(coalesce(p_identifier, ''));
  v_email text := btrim(coalesce(p_account_email, ''));
  v_code_hash text := btrim(coalesce(p_code_hash, ''));
  v_hash text := btrim(coalesce(p_token_hash, ''));
  v_user_id uuid;
begin
  if v_trimmed = '' or v_email = '' or v_code_hash = '' or v_hash = '' then
    raise exception 'VALIDATION_FAILED' using errcode = '22023';
  end if;

  -- The identifier is resolved the same way the login flow resolves it: an
  -- email is lower-cased and matched directly, a phone is normalised to E.164
  -- first. A reset requested with the phone number therefore reaches the same
  -- account as a reset requested with the email.
  if v_trimmed like '%@%' then
    select p.id into v_user_id
    from public.profiles p
    where lower(p.email) = lower(v_trimmed);
  else
    select p.id into v_user_id
    from public.profiles p
    where p.phone = public.normalise_bd_phone(v_trimmed);
  end if;

  if v_user_id is null then
    -- No account. The caller turns this into the same generic answer it
    -- gives for a real account, so the response never signals existence.
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;

  -- A soft-deleted account gets the generic answer too, and no challenge.
  -- The story's edge-case table: "the deleted account is not restored and no
  -- PII is disclosed".
  if exists (
    select 1 from public.profiles p
    where p.id = v_user_id and p.deleted_at is not null
  ) then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;

  -- A disabled account may still reset its password — it is locked out of
  -- the app, not out of its own credential. The story does not exclude it,
  -- and refusing here would strand a disabled user who cannot sign in to
  -- restore their own account.

  -- The previous challenge is superseded. This is what makes "only the
  -- newest challenge is valid" structural.
  update public.password_reset_challenges
     set consumed_at = now()
   where user_id = v_user_id
     and consumed_at is null;

  insert into public.password_reset_challenges (
    user_id,
    account_email,
    code_hash,
    token_hash,
    expires_at,
    attempts,
    cooldown_until,
    cooldown_expires_at,
    consumed_at
  ) values (
    v_user_id,
    v_email,
    v_code_hash,
    v_hash,
    now() + make_interval(mins => public.password_reset_otp_ttl_minutes()),
    0,
    null,
    null,
    null
  );

  return jsonb_build_object(
    'ok', true,
    'user_id', v_user_id,
    'expires_in_sec', public.password_reset_otp_ttl_minutes() * 60
  );
end;
$$;

revoke execute on function public.start_password_reset_otp(text, text, text, text) from public, anon, authenticated;
grant execute on function public.start_password_reset_otp(text, text, text, text) to service_role;

comment on function public.start_password_reset_otp(text, text, text, text) is
  'Records a password-reset OTP challenge: the bcrypt hash of the code, the GoTrue recovery token, and the accounting state. Service-role only — a client cannot call it.';

-- -----------------------------------------------------------------------------
-- check_password_reset_otp_state
-- -----------------------------------------------------------------------------
--
-- Decides whether an attempt may proceed, compares the code, and accounts for
-- a failed attempt.
--
-- This is the RPC that carries the story's server-side rules **and** the code
-- comparison. It is called **before** GoTrue is consulted, and it answers one
-- of three things:
--
--   * `ok`                     → the code was correct. The caller may now
--     redeem the GoTrue token.
--   * `OTP_RATE_LIMIT`         → the challenge is in cooldown. Every attempt
--     is refused, including a correct one, and the remaining wait comes
--     back in `retry_after_sec`.
--   * `VALIDATION_FAILED`      → the challenge is expired, gone, or the code
--     was wrong.
--
-- The submitted code
-- -----------------
-- `p_code` is the code the user typed. It is compared here, against
-- `code_hash`, and it is **never returned** in the result. The result
-- carries `token_hash` only on success — the GoTrue token that the caller
-- redeems once the code has been proven right.
--
-- The **failed** attempt is accounted for here too, through the
-- `p_attempt_ok` flag: the Edge Function calls this RPC twice — once before
-- the attempt with `p_attempt_ok = true`, and once after a failed attempt
-- with `p_attempt_ok = false`. The second call increments the counter and,
-- on the third failure, opens the cooldown.
--
-- The failures are **returned**, not raised
-- ------------------------------------------
-- The wrong-code path has to do two things at once: record the attempt, and
-- report the failure. A `raise exception` would do the second and undo the
-- first.
--
-- This is not a theoretical concern — it is exactly what the first
-- implementation did, and the attempt counter stayed at 0 after every
-- rejection. A function is one transaction: raising rolls the whole
-- transaction back, including the `update` that incremented `attempts`. The
-- three-attempt limit would then have been unenforceable, and the cooldown
-- would never have been reached.
--
-- So the failures are **returned** as a status in the result, and the
-- transaction commits.

create or replace function public.check_password_reset_otp_state(
  p_identifier text,
  p_code text default null,
  p_attempt_ok boolean default true
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public, extensions
as $$
declare
  v_trimmed text := btrim(coalesce(p_identifier, ''));
  v_code text := btrim(coalesce(p_code, ''));
  v_user_id uuid;
  v_challenge public.password_reset_challenges%rowtype;
  v_remaining integer;
  v_attempts integer;
  v_code_matches boolean := false;
begin
  if v_trimmed = '' then
    raise exception 'VALIDATION_FAILED' using errcode = '22023';
  end if;

  if v_trimmed like '%@%' then
    select p.id into v_user_id
    from public.profiles p
    where lower(p.email) = lower(v_trimmed);
  else
    select p.id into v_user_id
    from public.profiles p
    where p.phone = public.normalise_bd_phone(v_trimmed);
  end if;

  if v_user_id is null then
    -- No account, no challenge — the same generic failure a wrong code
    -- produces. No existence signal.
    return jsonb_build_object(
      'ok', false,
      'code', 'VALIDATION_FAILED',
      'reason', 'unknown_identifier'
    );
  end if;

  -- The live challenge for this account. At most one exists: the partial
  -- unique index enforces it.
  select * into v_challenge
  from public.password_reset_challenges c
  where c.user_id = v_user_id
    and c.consumed_at is null
  order by c.created_at desc
  limit 1
  for update;

  if not found then
    return jsonb_build_object(
      'ok', false,
      'code', 'VALIDATION_FAILED',
      'reason', 'no_challenge'
    );
  end if;

  -- The cooldown is checked **first**, before anything else.
  --
  -- That order is the point of the whole design: once the challenge is in
  -- cooldown, *every* attempt is rejected regardless of whether the code is
  -- right. A client that skips its own countdown cannot get in, and the
  -- rejection carries the remaining wait.
  if v_challenge.cooldown_until is not null
     and v_challenge.cooldown_expires_at is not null
     and now() < v_challenge.cooldown_expires_at then
    v_remaining := ceil(extract(epoch from (v_challenge.cooldown_expires_at - now())))::integer;
    return jsonb_build_object(
      'ok', false,
      'code', 'OTP_RATE_LIMIT',
      'reason', 'cooldown',
      'retry_after_sec', v_remaining,
      'attempts', v_challenge.attempts
    );
  end if;

  -- The validity window. An expired challenge is rejected, and the password
  -- is left alone.
  if now() >= v_challenge.expires_at then
    return jsonb_build_object(
      'ok', false,
      'code', 'VALIDATION_FAILED',
      'reason', 'expired'
    );
  end if;

  -- The code comparison.
  --
  -- This is the check the whole flow turns on. The code is compared here,
  -- server-side, against the bcrypt hash — and only a match unlocks the
  -- GoTrue token.
  --
  -- `p_attempt_ok = false` is the *accounting* call: it runs after a failure
  -- and does not compare a code.
  if p_attempt_ok is not false then
    if v_code = '' then
      return jsonb_build_object(
        'ok', false,
        'code', 'VALIDATION_FAILED',
        'reason', 'no_code'
      );
    end if;

    v_code_matches := (extensions.crypt(v_code, v_challenge.code_hash) = v_challenge.code_hash);

    if not v_code_matches then
      -- The failure is reported, not raised — see the note above. The
      -- attempt is counted in the `p_attempt_ok = false` call that follows.
      return jsonb_build_object(
        'ok', false,
        'code', 'VALIDATION_FAILED',
        'reason', 'wrong_code',
        'attempts', v_challenge.attempts,
        'attempts_remaining', greatest(
          public.password_reset_otp_max_attempts() - v_challenge.attempts,
          0
        )
      );
    end if;
  end if;

  -- A failed attempt is accounted for here. The increment and the cooldown
  -- check happen in one statement, so there is no window in which a
  -- concurrent attempt can slip past the limit.
  if p_attempt_ok is false then
    update public.password_reset_challenges
       set attempts = attempts + 1,
           cooldown_until = case
             when attempts + 1 >= public.password_reset_otp_max_attempts()
               then coalesce(cooldown_until, now())
             else cooldown_until
           end,
           cooldown_expires_at = case
             when attempts + 1 >= public.password_reset_otp_max_attempts()
               then coalesce(cooldown_expires_at, now() + make_interval(mins => public.password_reset_otp_cooldown_minutes()))
             else cooldown_expires_at
           end
     where id = v_challenge.id
     returning attempts into v_attempts;

    -- The challenge may have just entered its cooldown on this attempt, so
    -- the answer carries the remaining wait when it has.
    v_remaining := null;
    if v_attempts >= public.password_reset_otp_max_attempts() then
      select ceil(extract(epoch from (c.cooldown_expires_at - now())))::integer
        into v_remaining
        from public.password_reset_challenges c
       where c.id = v_challenge.id;

      return jsonb_build_object(
        'ok', false,
        'code', 'OTP_RATE_LIMIT',
        'reason', 'cooldown',
        'retry_after_sec', coalesce(v_remaining, 0),
        'attempts', v_attempts
      );
    end if;

    return jsonb_build_object(
      'ok', false,
      'code', 'VALIDATION_FAILED',
      'reason', 'wrong_code',
      'attempts', v_attempts,
      'attempts_remaining', public.password_reset_otp_max_attempts() - v_attempts
    );
  end if;

  -- The code was correct. The token comes back so the caller can redeem it
  -- with GoTrue — and GoTrue, and only GoTrue, turns it into a session.
  return jsonb_build_object(
    'ok', true,
    'user_id', v_user_id,
    'attempts', v_challenge.attempts,
    'attempts_remaining', public.password_reset_otp_max_attempts() - v_challenge.attempts,
    'expires_in_sec', greatest(0, ceil(extract(epoch from (v_challenge.expires_at - now())))::integer),
    'token_hash', v_challenge.token_hash,
    'account_email', v_challenge.account_email
  );
end;
$$;

revoke execute on function public.check_password_reset_otp_state(text, text, boolean) from public, anon, authenticated;
grant execute on function public.check_password_reset_otp_state(text, text, boolean) to service_role;

comment on function public.check_password_reset_otp_state(text, text, boolean) is
  'Compares a submitted password-reset code against the challenge''s bcrypt hash and enforces the 10-minute validity, the 3-attempt limit and the 30-minute cooldown server-side. Failures are RETURNED rather than raised, so the attempt counter survives the rejection. The GoTrue token is released only on a correct code. Service-role only.';

-- -----------------------------------------------------------------------------
-- consume_password_reset_otp
-- -----------------------------------------------------------------------------
--
-- Marks the challenge as used. Called after GoTrue has issued the session
-- and the password has been applied to it.
--
-- Without it a used code would stay valid until it expired, which is not
-- what "one-time code" means.

create or replace function public.consume_password_reset_otp(p_identifier text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_trimmed text := btrim(coalesce(p_identifier, ''));
  v_user_id uuid;
begin
  if v_trimmed = '' then
    raise exception 'VALIDATION_FAILED' using errcode = '22023';
  end if;

  if v_trimmed like '%@%' then
    select p.id into v_user_id
    from public.profiles p
    where lower(p.email) = lower(v_trimmed);
  else
    select p.id into v_user_id
    from public.profiles p
    where p.phone = public.normalise_bd_phone(v_trimmed);
  end if;

  if v_user_id is null then
    return jsonb_build_object('ok', false);
  end if;

  update public.password_reset_challenges
     set consumed_at = now()
   where user_id = v_user_id
     and consumed_at is null;

  return jsonb_build_object('ok', true, 'user_id', v_user_id);
end;
$$;

revoke execute on function public.consume_password_reset_otp(text) from public, anon, authenticated;
grant execute on function public.consume_password_reset_otp(text) to service_role;

comment on function public.consume_password_reset_otp(text) is
  'Marks the password-reset challenge as used. Service-role only.';

-- -----------------------------------------------------------------------------
-- The cleanup
-- -----------------------------------------------------------------------------
--
-- A consumed or expired challenge is dead weight. This keeps the table small
-- without needing a scheduled job for something this cheap.

create or replace function public.purge_expired_password_reset_challenges()
returns integer
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_removed integer;
begin
  delete from public.password_reset_challenges
   where (consumed_at is not null and consumed_at < now() - interval '1 day')
      or (expires_at < now() - interval '1 day');

  get diagnostics v_removed = row_count;
  return v_removed;
end;
$$;

revoke execute on function public.purge_expired_password_reset_challenges() from public, anon, authenticated;
grant execute on function public.purge_expired_password_reset_challenges() to service_role;

comment on function public.purge_expired_password_reset_challenges() is
  'Removes consumed and long-expired password-reset challenges. Service-role only.';
